// Writes packages/backend/src/login/packets.ts: the serverbound packet ids srvMC Login reads, per
// protocol version. minecraft-data is large (450 MB), so it is not a dependency; install it somewhere
// else and pass its folder:
//
//   npm i --prefix <tmp> minecraft-data --ignore-scripts
//   node scripts/gen-login-packets.mjs <tmp>/node_modules/minecraft-data [--report <protocol>=<packets.json>]...
//
// Versions newer than minecraft-data: run the server's own data generator and pass its report,
//   java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output out
//   ... --report 777=out/reports/packets.json
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const [mdDir, ...rest] = process.argv.slice(2);
if (!mdDir) {
  console.error('usage: node scripts/gen-login-packets.mjs <minecraft-data folder> [--report <protocol>=<packets.json>]...');
  process.exit(1);
}
const md = createRequire(import.meta.url)(path.resolve(mdDir));

// [chat message, chat command, signed chat command, configuration acknowledged (play), finish configuration (configuration)]
const NAMES = ['chat_message', 'chat_command', 'chat_command_signed', 'configuration_acknowledged'];
const out = {};

function idsOf(mapping) {
  const byName = Object.fromEntries(Object.entries(mapping ?? {}).map(([id, name]) => [name, Number(id)]));
  return byName;
}

for (const version of md.supportedVersions.pc) {
  const data = md(version);
  if (!data?.protocol?.play) continue;
  const proto = data.version.version;
  const mapper = (state, dir) => data.protocol[state]?.[dir]?.types?.packet?.[1]?.[0]?.type?.[1]?.mappings;
  const play = idsOf(mapper('play', 'toServer'));
  const cfg = idsOf(mapper('configuration', 'toServer'));
  // Before 1.19 every chat line, commands too, came as "chat".
  const row = [play.chat_message ?? play.chat ?? -1, play.chat_command ?? -1, play.chat_command_signed ?? -1, play.configuration_acknowledged ?? -1, cfg.finish_configuration ?? -1];
  out[proto] = row;
}

for (let i = 0; i < rest.length; i++) {
  if (rest[i] !== '--report') continue;
  const [proto, file] = rest[++i].split('=');
  const r = JSON.parse(readFileSync(file, 'utf8'));
  const p = (name) => r.play.serverbound[`minecraft:${name}`]?.protocol_id ?? -1;
  out[proto] = [p('chat'), p('chat_command'), p('chat_command_signed'), p('configuration_acknowledged'), r.configuration?.serverbound['minecraft:finish_configuration']?.protocol_id ?? -1];
}

const target = new URL('../packages/backend/src/login/packets.ts', import.meta.url);
const head = `// Generated by scripts/gen-login-packets.mjs – do not edit.\n// Per protocol: ${[...NAMES, 'finish_configuration'].join(', ')} (serverbound; -1 = none).\n`;
writeFileSync(target, `${head}export const PACKETS: Record<string, number[]> = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} protocol versions written to ${target.pathname}`);
